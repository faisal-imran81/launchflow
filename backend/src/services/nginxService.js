/**
 * @module nginxService
 *
 * Generates and manages Nginx reverse proxy configurations.
 * Supports static template generation, stack-aware configs, and SSL termination.
 *
 * Exported functions:
 *  - generateNginxConfig          — basic reverse proxy config from port + domain
 *  - generateNginxConfigFromStack — stack-aware config (frontend/backend/fullstack)
 *  - generateSslConfig            — HTTPS + SSL termination config
 *
 * @requires nginxErrors
 */

import { toNginxError } from '../utils/nginxErrors.js'
import { validateNginxConfig } from '../utils/validateNginxConfig.js'

/**
 * Logs validation errors and warnings for a generated Nginx config.
 *
 * @param {string} label - Identifier for log output e.g. domain name
 * @param {{ errors: string[], warnings: string[] }} result
 */
function logValidationResult(label, { errors, warnings }) {
  const tag = `[validateNginxConfig] ${label}`
  if (errors.length === 0 && warnings.length === 0) {
    console.log(`${tag} — validation passed`)
    return
  }
  console.warn(`${tag} — ${errors.length} error(s), ${warnings.length} warning(s)`)
  for (const msg of errors) console.error(`  ERROR: ${msg}`)
  for (const msg of warnings) console.warn(`  WARN: ${msg}`)
}

/**
 * Generates a basic Nginx reverse proxy config.
 *
 * @param {object} options
 * @param {string} options.domain      - Domain or server name e.g. "example.com"
 * @param {number|string} options.port - Backend port to proxy to e.g. 3000
 * @param {string} [options.appName]   - Optional app name for comments
 * @returns {{ config: string }}
 */
export function generateNginxConfig({ domain, port, appName = 'app' } = {}) {
  if (!domain || typeof domain !== 'string') {
    const err = new Error('domain is required and must be a string')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if (!port) {
    const err = new Error('port is required')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const numPort = Number(port)
  if (isNaN(numPort) || numPort < 1 || numPort > 65535) {
    const err = new Error('port must be a valid number between 1 and 65535')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const config = `# Nginx reverse proxy config for ${appName}
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    # Proxy all requests to the app
    location / {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }
}
`

  logValidationResult(domain, validateNginxConfig(config))
  return { config }
}

/**
 * Generates a stack-aware Nginx config based on the detected stack type.
 * - frontend: serves static files from a build directory
 * - backend: reverse proxy to a Node.js server
 * - fullstack: reverse proxy with /api prefix routing
 *
 * @param {object} options
 * @param {string} options.domain      - Domain or server name e.g. "example.com"
 * @param {string} options.type        - Stack type: "frontend" | "backend" | "fullstack"
 * @param {number|string} [options.port] - Backend port (required for backend/fullstack)
 * @param {string} [options.buildOutput] - Build output folder (required for frontend) e.g. "dist"
 * @param {string} [options.appName]   - Optional app name for comments
 * @returns {{ config: string }}
 */
export function generateNginxConfigFromStack({ domain, type, port, buildOutput = 'dist', appName = 'app' } = {}) {
  if (!domain || typeof domain !== 'string') {
    const err = new Error('domain is required and must be a string')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if (!type || !['frontend', 'backend', 'fullstack'].includes(type)) {
    const err = new Error('type must be one of: frontend, backend, fullstack')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if ((type === 'backend' || type === 'fullstack') && !port) {
    const err = new Error('port is required for backend and fullstack types')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const numPort = port ? Number(port) : null

  if (type === 'frontend') {
    const config = `# Nginx static file server for ${appName} (frontend)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    root /usr/share/nginx/html/${buildOutput};
    index index.html;

    # SPA fallback — serve index.html for all routes
    location / {
        try_files $uri $uri/ /index.html;
    }

    # Cache static assets aggressively
    location ~* \\.(?:ico|css|js|gif|jpe?g|png|woff2?)$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
}
`
    logValidationResult(domain, validateNginxConfig(config))
    return { config }
  }

  if (type === 'backend') {
    const config = `# Nginx reverse proxy for ${appName} (backend)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    location / {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }
}
`
    logValidationResult(domain, validateNginxConfig(config))
    return { config }
  }

  // fullstack — static frontend + /api proxy
  const config = `# Nginx config for ${appName} (fullstack)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    # Serve frontend static files
    root /usr/share/nginx/html/${buildOutput};
    index index.html;

    # Proxy API requests to the backend
    location /api/ {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }

    # SPA fallback for all other routes
    location / {
        try_files $uri $uri/ /index.html;
    }
}
`
  logValidationResult(domain, validateNginxConfig(config))
  return { config }
}

/**
 * Generates an Nginx HTTPS config with SSL termination.
 * Includes HTTP → HTTPS redirect and strong SSL settings.
 * Assumes certificates are managed by Certbot / Let's Encrypt.
 *
 * @param {object} options
 * @param {string} options.domain        - Domain name e.g. "example.com"
 * @param {number|string} options.port   - Backend port to proxy to e.g. 3000
 * @param {string} [options.appName]     - Optional app name for comments
 * @param {string} [options.certPath]    - Path to SSL cert (defaults to Let's Encrypt path)
 * @param {string} [options.keyPath]     - Path to SSL key (defaults to Let's Encrypt path)
 * @returns {{ config: string }}
 */
export function generateSslConfig({
  domain,
  port,
  appName = 'app',
  certPath,
  keyPath,
} = {}) {
  if (!domain || typeof domain !== 'string') {
    const err = new Error('domain is required and must be a string')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if (!port) {
    const err = new Error('port is required')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const numPort = Number(port)
  if (isNaN(numPort) || numPort < 1 || numPort > 65535) {
    const err = new Error('port must be a valid number between 1 and 65535')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const resolvedCert = certPath ?? `/etc/letsencrypt/live/${domain}/fullchain.pem`
  const resolvedKey  = keyPath  ?? `/etc/letsencrypt/live/${domain}/privkey.pem`

  const config = `# Nginx HTTPS config for ${appName}
# Generated by LaunchFlow
# Certificates managed by Certbot / Let's Encrypt

# HTTP → HTTPS redirect
server {
    listen 80;
    server_name ${domain};
    return 301 https://$host$request_uri;
}

# HTTPS server
server {
    listen 443 ssl;
    server_name ${domain};

    ssl_certificate     ${resolvedCert};
    ssl_certificate_key ${resolvedKey};

    # Strong SSL settings
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 1d;

    # Security headers
    add_header Strict-Transport-Security "max-age=63072000; includeSubDomains; preload" always;
    add_header X-Frame-Options DENY;
    add_header X-Content-Type-Options nosniff;

    location / {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }
}
`

  logValidationResult(domain, validateNginxConfig(config))
  return { config }
}
