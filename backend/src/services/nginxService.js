/**
 * @module nginxService
 *
 * Generates and manages Nginx reverse proxy configurations.
 * Supports static template generation, stack-aware configs, and SSL termination.
 *
 * Exported functions:
 *  - generateNginxConfig          — basic reverse proxy config from port + domain
 *  - generateNginxConfigFromStack — stack-aware config (frontend/backend/fullstack)
 *  - generateSslConfig            — HTTPS + SSL termination config
 *
 * @requires nginxErrors
 */

import { toNginxError } from '../utils/nginxErrors.js'

/**
 * Generates a basic Nginx reverse proxy config.
 *
 * @param {object} options
 * @param {string} options.domain      - Domain or server name e.g. "example.com"
 * @param {number|string} options.port - Backend port to proxy to e.g. 3000
 * @param {string} [options.appName]   - Optional app name for comments
 * @returns {{ config: string }}
 */
export function generateNginxConfig({ domain, port, appName = 'app' } = {}) {
  if (!domain || typeof domain !== 'string') {
    const err = new Error('domain is required and must be a string')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if (!port) {
    const err = new Error('port is required')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const numPort = Number(port)
  if (isNaN(numPort) || numPort < 1 || numPort > 65535) {
    const err = new Error('port must be a valid number between 1 and 65535')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const config = `# Nginx reverse proxy config for ${appName}
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    # Proxy all requests to the app
    location / {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }
}
`

  return { config }
}

/**
 * Generates a stack-aware Nginx config based on the detected stack type.
 * - frontend: serves static files from a build directory
 * - backend: reverse proxy to a Node.js server
 * - fullstack: reverse proxy with /api prefix routing
 *
 * @param {object} options
 * @param {string} options.domain      - Domain or server name e.g. "example.com"
 * @param {string} options.type        - Stack type: "frontend" | "backend" | "fullstack"
 * @param {number|string} [options.port] - Backend port (required for backend/fullstack)
 * @param {string} [options.buildOutput] - Build output folder (required for frontend) e.g. "dist"
 * @param {string} [options.appName]   - Optional app name for comments
 * @returns {{ config: string }}
 */
export function generateNginxConfigFromStack({ domain, type, port, buildOutput = 'dist', appName = 'app' } = {}) {
  if (!domain || typeof domain !== 'string') {
    const err = new Error('domain is required and must be a string')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if (!type || !['frontend', 'backend', 'fullstack'].includes(type)) {
    const err = new Error('type must be one of: frontend, backend, fullstack')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  if ((type === 'backend' || type === 'fullstack') && !port) {
    const err = new Error('port is required for backend and fullstack types')
    err.status = 400
    err.code = 'nginx/invalid-input'
    throw err
  }

  const numPort = port ? Number(port) : null

  if (type === 'frontend') {
    const config = `# Nginx static file server for ${appName} (frontend)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    root /usr/share/nginx/html/${buildOutput};
    index index.html;

    # SPA fallback — serve index.html for all routes
    location / {
        try_files $uri $uri/ /index.html;
    }

    # Cache static assets aggressively
    location ~* \\.(?:ico|css|js|gif|jpe?g|png|woff2?)$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
}
`
    return { config }
  }

  if (type === 'backend') {
    const config = `# Nginx reverse proxy for ${appName} (backend)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    location / {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }
}
`
    return { config }
  }

  // fullstack — static frontend + /api proxy
  const config = `# Nginx config for ${appName} (fullstack)
# Generated by LaunchFlow

server {
    listen 80;
    server_name ${domain};

    # Serve frontend static files
    root /usr/share/nginx/html/${buildOutput};
    index index.html;

    # Proxy API requests to the backend
    location /api/ {
        proxy_pass http://localhost:${numPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_cache_bypass $http_upgrade;
    }

    # SPA fallback for all other routes
    location / {
        try_files $uri $uri/ /index.html;
    }
}
`
  return { config }
}
